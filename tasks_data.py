LEVELS = {
    "low": {"name": "Бастапқы", "range": (0, 4)},
    "mid": {"name": "Орта", "range": (5, 7)},
    "high": {"name": "Жоғары", "range": (8, 10)},
}
LEVEL_ORDER = ["low", "mid", "high"]


def level_for_score(score):
    """Тест балы бойынша деңгей: 0–4 — бастапқы, 5–7 — орта, 8–10 — жоғары."""
    for key in LEVEL_ORDER:
        lo, hi = LEVELS[key]["range"]
        if lo <= score <= hi:
            return key
    return "high"


def crit(name, l0, l1, l2):
    return {"name": name, "max": 2, "levels": [l0, l1, l2]}


